        public static long GetWindowStyle(IntPtr hWnd)
            => IntPtr.Size == 8 ? GetWindowLongPtr64(hWnd, GWL_EXSTYLE).ToInt64() : GetWindowLong32(hWnd, GWL_EXSTYLE).ToInt64();

        public static void SetWindowStyleFlag(IntPtr hWnd, long flag, bool enable)
        {
            long style = GetWindowStyle(hWnd);
            long newStyle = enable ? style | flag : style & ~flag;
            if (IntPtr.Size == 8) SetWindowLongPtr64(hWnd, GWL_EXSTYLE, new IntPtr(newStyle));
            else SetWindowLong32(hWnd, GWL_EXSTYLE, new IntPtr(newStyle));
        }

